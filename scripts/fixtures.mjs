// Generates src/testing/fixtures/*.ts from testdata/fixtures/ (design 002 E16): the browser
// fakes and the Vitest specs get the real Icon Composer files without file access.
//
//   node scripts/fixtures.mjs          write the modules
//   node scripts/fixtures.mjs --check  fail if a module is out of date
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * Fixtures → generated module (relative to the repo root): `.icon` bundles, the folder of SVG
 * fixtures (design 003: round trip of every SVG) and the table of unique names (002 E12).
 */
export const MODULES = [
  {
    bundle: 'testdata/fixtures/camscanner.icon',
    out: 'src/testing/fixtures/camscanner-icon.ts',
    constName: 'CAMSCANNER_ICON',
  },
  {
    svgDir: 'testdata/fixtures/svg',
    out: 'src/testing/fixtures/svg-fixtures.ts',
    constName: 'SVG_FIXTURES',
  },
  {
    json: 'testdata/unique-names.json',
    out: 'src/testing/fixtures/unique-names.ts',
    constName: 'UNIQUE_NAMES',
  },
];

async function format(root, source) {
  const options = (await prettier.resolveConfig(join(root, 'src/testing/x.ts'))) ?? {};
  return prettier.format(source, { ...options, parser: 'typescript' });
}

/** Module source of one entry of {@link MODULES}. */
export async function render(root, m) {
  if (m.svgDir) {
    const files = readdirSync(join(root, m.svgDir))
      .filter((n) => n.toLowerCase().endsWith('.svg'))
      .sort()
      .map((n) => ({ name: n, text: readFileSync(join(root, m.svgDir, n), 'utf8') }));
    return format(
      root,
      `// Generated by scripts/fixtures.mjs from ${m.svgDir} – do not edit (pnpm fixtures).
export const ${m.constName}: { name: string; text: string }[] = ${JSON.stringify(files)};
`,
    );
  }
  if (m.json) {
    const data = JSON.parse(readFileSync(join(root, m.json), 'utf8'));
    return format(
      root,
      `// Generated by scripts/fixtures.mjs from ${m.json} – do not edit (pnpm fixtures).
interface NameCase {
  base: string;
  existing: string[];
  expected: string;
}

export const ${m.constName}: { asset: NameCase[]; layer: NameCase[] } = ${JSON.stringify({ asset: data.asset, layer: data.layer })};
`,
    );
  }
  return renderBundle(root, m);
}

/** Module source for one bundle: icon.json and every SVG asset as text. */
async function renderBundle(root, { bundle, constName }) {
  const dir = join(root, bundle);
  const name = bundle.split('/').pop();
  const iconJson = readFileSync(join(dir, 'icon.json'), 'utf8');
  const assets = readdirSync(join(dir, 'Assets'))
    .filter((n) => n.toLowerCase().endsWith('.svg'))
    .sort()
    .map((n) => ({ name: n, text: readFileSync(join(dir, 'Assets', n), 'utf8') }));
  const source = `// Generated by scripts/fixtures.mjs from ${bundle} – do not edit (pnpm fixtures).
import { FixtureIcon } from './fixture-icon';

export const ${constName}: FixtureIcon = ${JSON.stringify({ name, iconJson, assets })};
`;
  return format(root, source);
}

/** Names of modules whose file differs from what would be generated. */
export async function outdated(root = ROOT) {
  const stale = [];
  for (const m of MODULES) {
    const file = join(root, m.out);
    const want = await render(root, m);
    if (!existsSync(file) || readFileSync(file, 'utf8') !== want) stale.push(m.out);
  }
  return stale;
}

async function main() {
  if (process.argv.includes('--check')) {
    const stale = await outdated();
    if (stale.length) {
      console.error(`out of date (run pnpm fixtures): ${stale.join(', ')}`);
      process.exit(1);
    }
    return;
  }
  for (const m of MODULES) writeFileSync(join(ROOT, m.out), await render(ROOT, m));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
