import { NodeSetProvider, PHOSPHOR, SetData, TABLER } from './node-set-provider';

const DATA: SetData = {
  set: 'test',
  version: '1.0.0',
  size: 24,
  nodes: {
    heart: ['M2 9.5a5.5 5.5 0 0 1 9.591-3.676Z'],
    dot: [['path', { d: 'M11 11h2v2h-2z', fill: 'currentColor', onclick: 'alert(1)' }]],
    ring: [['circle', { cx: '12', cy: '12', r: '10' }]],
  },
  tags: { heart: ['love'], dot: ['point'] },
};

const license = { name: 'MIT License', spdx: 'MIT', url: 'https://example.org', package: 'x' };

describe('NodeSetProvider (design 084 E2/E3)', () => {
  it('a stroke set: one group with the weight, every element a path, handlers dropped', async () => {
    const p = new NodeSetProvider({
      id: 't',
      name: 'T',
      license,
      paint: 'stroke',
      weight: { key: 'weight', label: 'Weight', min: 0.5, max: 3, step: 0.25, default: 2 },
      load: () => Promise.resolve(DATA),
    });
    expect(p.loaded).toBe(false);
    await p.load();
    expect(p.search('love', 10).items.map((s) => s.id)).toEqual(['heart']);
    expect(p.all().map((s) => s.id)).toEqual(['dot', 'heart', 'ring']);
    const s = p.toSvg('dot', { weight: 1.5 })!;
    expect(s.group.attrs).toMatchObject({ fill: 'none', stroke: '#000000', 'stroke-width': '1.5' });
    expect(s.group.children![0].attrs).toEqual({ d: 'M11 11h2v2h-2z', fill: '#000000' });
    expect(s.markup).not.toContain('onclick');
    expect(p.toSvg('ring')!.group.children![0].attrs['d']).toMatch(/^M2 12A10 10/);
    expect(p.toSvg('nope')).toBeNull();
    expect(p.toSvg('constructor')).toBeNull();
  });

  it('a fill set: filled paths, no variant, its own size', async () => {
    const p = new NodeSetProvider({
      id: 'f',
      name: 'F',
      license,
      paint: 'fill',
      load: () => Promise.resolve({ ...DATA, size: 256 }),
    });
    await p.load();
    expect(p.variants).toEqual([]);
    const s = p.toSvg('heart', { weight: 3 })!;
    expect(s.width).toBe(256);
    expect(s.group.attrs).toEqual({ fill: '#000000' });
    expect(s.markup).toContain('viewBox="0 0 256 256"');
  });

  it('a failed load can be retried', async () => {
    let fail = true;
    const p = new NodeSetProvider({
      id: 'r',
      name: 'R',
      license,
      paint: 'fill',
      load: () => (fail ? Promise.reject(new Error('x')) : Promise.resolve(DATA)),
    });
    await expect(p.load()).rejects.toThrow('x');
    fail = false;
    await p.load();
    expect(p.loaded).toBe(true);
  });
});

describe('the real Tabler and Phosphor data (generated by scripts/symbol-data.mjs)', () => {
  it('Tabler: thousands of outline icons, every element a path', async () => {
    await TABLER.load();
    const all = TABLER.search('', 100_000);
    expect(all.total).toBeGreaterThan(4000);
    for (const s of all.items) {
      const svg = TABLER.toSvg(s.id)!;
      expect(svg.group.children!.length, s.id).toBeGreaterThan(0);
      expect(svg.group.children!.every((c) => c.tag === 'path' && c.attrs['d'])).toBe(true);
    }
    expect(TABLER.search('heart', 5).items[0].id).toBe('heart');
    expect(TABLER.toSvg('heart')!.group.attrs['stroke-width']).toBe('2');
  });

  it('Phosphor: the regular weight, filled', async () => {
    await PHOSPHOR.load();
    const all = PHOSPHOR.search('', 100_000);
    expect(all.total).toBeGreaterThan(1000);
    for (const s of all.items) {
      expect(PHOSPHOR.toSvg(s.id)!.group.children!.length, s.id).toBeGreaterThan(0);
    }
    expect(PHOSPHOR.search('heart', 5).items[0].id).toBe('heart');
    expect(PHOSPHOR.toSvg('heart')!.width).toBe(256);
  });
});
